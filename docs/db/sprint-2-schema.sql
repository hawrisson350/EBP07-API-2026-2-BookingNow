ALTER TABLE bookingnow.servicios
    ADD COLUMN IF NOT EXISTS tipo_servicio varchar(100),
    ADD COLUMN IF NOT EXISTS requiere_empleados boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS requiere_recursos boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS bookingnow.recursos (
    id_recurso bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_negocio bigint NOT NULL REFERENCES bookingnow.negocios(id_negocio),
    nombre varchar(255) NOT NULL,
    cantidad integer NOT NULL CHECK (cantidad > 0),
    estado varchar(24) NOT NULL CHECK (estado IN ('DISPONIBLE','NO_DISPONIBLE','MANTENIMIENTO')),
    descripcion varchar(2000) NOT NULL
);

CREATE TABLE IF NOT EXISTS bookingnow.empleados (
    id_empleado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_negocio bigint NOT NULL REFERENCES bookingnow.negocios(id_negocio),
    nombres varchar(255) NOT NULL,
    documento varchar(32) NOT NULL,
    telefono varchar(25) NOT NULL,
    correo varchar(255) NOT NULL,
    CONSTRAINT uq_empleado_negocio_documento UNIQUE (id_negocio, documento)
);

CREATE TABLE IF NOT EXISTS bookingnow.horarios_atencion (
    id_horario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_negocio bigint NOT NULL REFERENCES bookingnow.negocios(id_negocio),
    dia_semana varchar(12) NOT NULL CHECK (dia_semana IN ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    hora_apertura time NOT NULL,
    hora_cierre time NOT NULL,
    CONSTRAINT uq_horario_negocio_dia UNIQUE (id_negocio, dia_semana),
    CHECK (hora_cierre > hora_apertura)
);

CREATE TABLE IF NOT EXISTS bookingnow.servicio_empleados (
    id_servicio bigint NOT NULL REFERENCES bookingnow.servicios(id_servicio) ON DELETE CASCADE,
    id_empleado bigint NOT NULL REFERENCES bookingnow.empleados(id_empleado),
    PRIMARY KEY (id_servicio, id_empleado)
);

CREATE TABLE IF NOT EXISTS bookingnow.servicio_recursos (
    id_servicio bigint NOT NULL REFERENCES bookingnow.servicios(id_servicio) ON DELETE CASCADE,
    id_recurso bigint NOT NULL REFERENCES bookingnow.recursos(id_recurso),
    PRIMARY KEY (id_servicio, id_recurso)
);

CREATE TABLE IF NOT EXISTS bookingnow.reservas (
    id_reserva bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente bigint NOT NULL REFERENCES bookingnow.clientes(id_cliente),
    id_servicio bigint NOT NULL REFERENCES bookingnow.servicios(id_servicio),
    id_empleado bigint REFERENCES bookingnow.empleados(id_empleado),
    id_recurso bigint REFERENCES bookingnow.recursos(id_recurso),
    fecha date NOT NULL,
    hora time NOT NULL,
    estado varchar(32) NOT NULL CHECK (estado IN ('PENDIENTE_CONFIRMACION','CONFIRMADA','CANCELADA')),
    fecha_creacion timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_reservas_fecha_hora ON bookingnow.reservas(fecha,hora);
CREATE INDEX IF NOT EXISTS ix_reservas_empleado_fecha ON bookingnow.reservas(id_empleado,fecha);
CREATE INDEX IF NOT EXISTS ix_reservas_recurso_fecha ON bookingnow.reservas(id_recurso,fecha);

ALTER TABLE bookingnow.recursos ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookingnow.empleados ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookingnow.horarios_atencion ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookingnow.servicio_empleados ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookingnow.servicio_recursos ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookingnow.reservas ENABLE ROW LEVEL SECURITY;
CREATE TABLE IF NOT EXISTS bookingnow.servicio_imagenes (
    id_servicio bigint NOT NULL REFERENCES bookingnow.servicios(id_servicio) ON DELETE CASCADE,
    orden integer NOT NULL,
    contenido_base64 text NOT NULL,
    PRIMARY KEY (id_servicio, orden)
);
